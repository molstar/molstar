import type { Node } from '@molstar/core/repr/tree';
import type { SeqRegistryEntry } from '@molstar/seqx-core/context';
import { createSeqSpec, ideogramNavigator } from '@molstar/seqx-core/lang';
import { chr17BandsSource } from '../navigators.js';
import {
  ChromosomeFormat,
  type ChromosomeOptions,
  chromosomeRuntime,
  ChromosomeSystem,
  DefaultChromosome,
} from './chromosome-data.js';
import { delayedRegistry, type RegistryOptions } from './gene-by-region.js';

// p53's chromosome, the p53 dataset's genome-level view: chromosome 17 generated by region, opened fit to its 83 Mb. A
// ruler, the genes (a row each, both strands; a density at the coarse levels), each gene's exons as it arrives with
// its region (a gene a dynamic node, its exons a ranges node of its nested source, a track each by a template), a GC-like signal by bin-width levels, the letters when they fit; chr17's ideogram above
// shows the window. Double-click TP53 to focus it, zoom on to its letters.

export const title = 'p53’s chromosome';

/** The section's address, and its layers' (what the tests and the story read). */
export const Section = '/views/main/chr17';
export const GenesLayer = `${Section}/genes/ranges`;

/** The view's spec. */
export function build(): Node {
  const b = createSeqSpec({ title });
  const source = b.data.source('chr17-generated', { format: ChromosomeFormat, uri: 'generated:chr17' });
  const chr = b.data.sequence('chr17', { alphabet: 'dna', source, name: ChromosomeSystem });
  const genes = b.data.ranges('genes', { target: chr, source });
  const gc = b.data.values('gc', { target: chr, source });
  const bands = b.data.ranges('chr17-bands', { target: chr, source: chr17BandsSource(b) });
  b.views.view('main', (v) => {
    const s = v.section('chr17', { of: chr });
    s.track('ruler', { label: '' }).layer('ruler', { type: 'ruler' });
    s.track('genes', { label: 'Genes' }).layer('ranges', { type: 'ranges', data: genes });
    s.track('exons', { label: 'Exons', for_each: { source, node_kind: 'ranges', depth: 1 } }).layer('ranges', {
      type: 'ranges',
    });
    s.track('gc', { label: 'GC' }).layer('values', { type: 'values', data: gc });
    s.track('letters', { label: 'chr17' }).layer('letters', { type: 'letters' });
    v.navigator('chr17', ideogramNavigator(s, bands));
  });
  return b.build();
}

/** What the view needs besides the default registry: the chromosome's runtime, each answer after `delayMs` (150). */
export function registry(
  options: RegistryOptions & { readonly chromosome?: ChromosomeOptions } = {},
): SeqRegistryEntry[] {
  return delayedRegistry(chromosomeRuntime(options.chromosome ?? DefaultChromosome), 'chromosome', ChromosomeFormat, {
    ...options,
    delayMs: options.delayMs ?? 150,
  });
}
