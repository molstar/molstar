import { PCG } from '@molstar/core/data/util/hash-functions';
import { categoryColumn, issueOf } from '@molstar/core/repr/tree';
import {
  abortError,
  type Coverage,
  type DynamicNode,
  type FormatRuntime,
  type RegionAnswer,
  type RegionRequest,
  SourceIssues,
  type Tables,
} from '@molstar/seqx-core/data';
import { Chr17Length } from '../navigators.js';
import { GeneExons, GeneLength, geneLetters } from './data.js';
import { exonsNode } from './region.js';

// p53's chromosome, the p53 dataset's genome-level view: chromosome 17 at its GRCh38 length, every byte generated by
// region and never stored. The letters come a block at a time from core's `PCG` seeded by the block's index (their GC
// share following the signal), so a region's letters never depend on what was asked before; TP53's span carries the
// dataset's gene (`tp53-gene.seq`'s letters at its start). Genes are generated a megabase block at a time from the
// seed (both strands, exons), TP53 placed as built; a region's answer lists the genes it overlaps as ranges at every
// level and, at the fine levels (`NodesLevel`), brings each one's exons as a dynamic node. The signal is GC-like: smooth waves and noise at
// level 1, the waves' exact mean over each bin at the coarser levels (the noise's bounds as min and max).

/** The generator's options: `chromosome.length`, `.genes`, `.seed`. */
export interface ChromosomeOptions {
  /** Positions: GRCh38's chr17 by default. */
  readonly length: number;
  /** About how many genes: 1,200 by default. */
  readonly genes: number;
  readonly seed: number;
}

export const DefaultChromosome: ChromosomeOptions = { length: Chr17Length, genes: 1200, seed: 17 };

/** The format a view names: the application gives it the runtime (`chromosomeRuntime`). */
export const ChromosomeFormat = 'chromosome';
export const ChromosomeSystem = 'chr17';
/** The sequence's address in the view's spec: the genes' exons are on it. */
export const ChromosomeSequence = '/data/chr17';
/**
 * Bin widths served, 4 apart up to 4^13 (the whole chromosome in two tiles): a layer reads at most 4 bins a device
 * column (the Performance page, Levels and a frame's cost): 16 apart, the store's factor, a frame between two levels and at
 * TP53 cost two to three times as much, the signal reading up to 16 bins a column.
 */
export const ChromosomeLevels: readonly number[] = Array.from({ length: 14 }, (_, i) => 4 ** i);

/**
 * TP53 on chr17 (GRCh38: 7,668,402–7,687,550, minus strand, 1-based and inclusive: `[7_668_401, 7_687_550)` here,
 * 0-based), its exons the dataset's gene's at its start.
 */
export const Tp53 = {
  name: 'TP53',
  start: 7_668_401,
  end: 7_687_550,
  strand: -1 as const,
  exons: GeneExons.start.map((s, i) => [7_668_401 + s, 7_668_401 + GeneExons.end[i]] as [number, number]),
};

/** The coarsest level whose answers bring the genes' exons as nodes: a view of up to about 160 kb at 1,440 px. */
export const NodesLevel = 16;
/** Positions a block of letters covers (one generator each). */
export const LetterBlock = 4096;
/** Positions a block of genes covers (one generator each); a gene starts in its block and may run past it. */
export const GeneBlock = 1_000_000;
const MinGene = 2_000;
const MaxGene = 60_000;
/** Genes kept clear of TP53's span on each side. */
const Tp53Clear = 10_000;
/** The signal's noise at level 1: ± this much. */
const Noise = 0.05;

export interface Gene {
  readonly name: string;
  readonly start: number;
  readonly end: number;
  readonly strand: 1 | -1;
  /** Genomic order, inside `[start, end)`, the first at `start` and the last at `end`. */
  readonly exons: readonly (readonly [number, number])[];
}

/** A block's generator: its own seed from the chromosome's, the block's index and what it makes (`salt`). */
function blockRng(seed: number, block: number, salt: number): PCG {
  const rng = new PCG((seed ^ Math.imul(block + 1, 0x9e3779b1) ^ Math.imul(salt, 0x85ebca6b)) >>> 0);
  // the first outputs of nearby seeds are alike: let the state mix
  rng.int();
  rng.int();
  return rng;
}

/** A generated chromosome: what its regions answer, made on each request. */
export interface Chromosome {
  readonly options: ChromosomeOptions;
  readonly coverage: Coverage;
  /** The genes overlapping `[start, end)`, by start. */
  genesIn(start: number, end: number): Gene[];
  letters(start: number, end: number): string;
  /** The signal's mean over `[a, b)`, its noise aside. */
  smoothMean(a: number, b: number): number;
  answer(request: RegionRequest): RegionAnswer;
}

export function chromosome(options: ChromosomeOptions = DefaultChromosome): Chromosome {
  const { length, seed } = options;
  const coverage: Coverage = {
    systems: [{ name: ChromosomeSystem, length, alphabet: 'dna', aliases: ['17'] }],
    shapes: [
      { system: ChromosomeSystem, shape: 'letters' },
      { system: ChromosomeSystem, shape: 'ranges' },
      { system: ChromosomeSystem, shape: 'values' },
    ],
    levels: ChromosomeLevels,
  };
  // the signal's waves: 7.3 Mb, 1.1 Mb and 170 kb, their phases from the seed
  const waves = (() => {
    const rng = blockRng(seed, -1, 0);
    return [
      { amp: 0.06, w: (2 * Math.PI) / 7_300_000, phase: 2 * Math.PI * rng.float() },
      { amp: 0.04, w: (2 * Math.PI) / 1_100_000, phase: 2 * Math.PI * rng.float() },
      { amp: 0.03, w: (2 * Math.PI) / 170_000, phase: 2 * Math.PI * rng.float() },
    ];
  })();
  const smoothMean = (a: number, b: number) => {
    let v = 0.45;
    // the mean of sin(w x + phase) over [a, b), exactly: bins of every level agree
    for (const { amp, w, phase } of waves)
      v += (amp * (Math.cos(w * a + phase) - Math.cos(w * b + phase))) / (w * (b - a));
    return v;
  };
  const tp53Letters = geneLetters();

  const blockGenes = (block: number): Gene[] => {
    const b0 = block * GeneBlock;
    const b1 = Math.min(length, b0 + GeneBlock);
    if (b1 - b0 < MinGene) return [];
    const rng = blockRng(seed, block, 1);
    const n = Math.round(((options.genes * (b1 - b0)) / length) * (0.5 + rng.float()));
    const out: Gene[] = [];
    for (let k = 0; k < n; k++) {
      const start = b0 + Math.floor(rng.float() * (b1 - b0 - MinGene));
      const end = Math.min(length, start + Math.round(MinGene * (MaxGene / MinGene) ** rng.float()));
      const strand = rng.int() & 1 ? 1 : -1;
      const count = 2 + (rng.int() % 9);
      const slot = (end - start) / count;
      const exons: [number, number][] = [];
      for (let i = 0; i < count; i++) {
        const lo = start + Math.floor(i * slot);
        const hi = i === count - 1 ? end : start + Math.floor((i + 1) * slot);
        const e = Math.min(hi - lo, 60 + Math.floor(rng.float() * 240));
        const at = i === 0 ? lo : i === count - 1 ? hi - e : lo + Math.floor(rng.float() * (hi - lo - e));
        exons.push([at, at + e]);
      }
      out.push({ name: `G${block}.${k + 1}`, start, end, strand, exons });
    }
    if (Tp53.start < b1 && Tp53.end > b0) {
      const kept = out.filter((g) => g.end <= Tp53.start - Tp53Clear || g.start >= Tp53.end + Tp53Clear);
      kept.push(Tp53);
      kept.sort((a, b) => a.start - b.start);
      return kept;
    }
    return out;
  };

  const genesIn = (start: number, end: number): Gene[] => {
    const out: Gene[] = [];
    const first = Math.max(0, Math.floor((start - MaxGene) / GeneBlock));
    const last = Math.floor((end - 1) / GeneBlock);
    for (let block = first; block <= last; block++)
      for (const g of blockGenes(block)) if (g.start < end && g.end > start) out.push(g);
    return out.sort((a, b) => a.start - b.start);
  };

  const letters = (start: number, end: number): string => {
    const codes = new Uint8Array(Math.max(0, end - start));
    for (let block = Math.floor(start / LetterBlock); block * LetterBlock < end; block++) {
      const b0 = block * LetterBlock;
      const b1 = Math.min(length, b0 + LetterBlock);
      // the block's GC share is the signal's there
      const gc = smoothMean(b0, b1);
      const rng = blockRng(seed, block, 2);
      for (let p = b0; p < b1; p++) {
        const r = rng.int();
        if (p < start || p >= end) continue;
        const strong = (r >>> 8) / 0x1000000 < gc;
        codes[p - start] = strong ? (r & 1 ? 71 : 67) : r & 1 ? 84 : 65;
      }
    }
    // TP53's span carries the dataset's gene
    const t0 = Math.max(start, Tp53.start);
    const t1 = Math.min(end, Tp53.start + GeneLength);
    for (let p = t0; p < t1; p++) codes[p - start] = tp53Letters.charCodeAt(p - Tp53.start);
    let s = '';
    for (let i = 0; i < codes.length; i += 4096) s += String.fromCharCode(...codes.subarray(i, i + 4096));
    return s;
  };

  const values = (start: number, end: number, level: number): Tables['values'] => {
    if (level === 1) {
      const value = new Float32Array(end - start);
      for (let block = Math.floor(start / LetterBlock); block * LetterBlock < end; block++) {
        const b0 = block * LetterBlock;
        const b1 = Math.min(length, b0 + LetterBlock);
        const rng = blockRng(seed, block, 3);
        for (let p = b0; p < b1; p++) {
          const noise = (rng.float() - 0.5) * 2 * Noise;
          if (p >= start && p < end) value[p - start] = smoothMean(p, p + 1) + noise;
        }
      }
      return { form: 'positions', start, value };
    }
    const from = Math.floor(start / level) * level;
    const n = Math.max(0, Math.ceil(Math.min(end, length) / level) - from / level);
    const mean = new Float32Array(n);
    const min = new Float32Array(n);
    const max = new Float32Array(n);
    const count = new Float32Array(n);
    for (let i = 0; i < n; i++) {
      const a = from + i * level;
      const b = Math.min(length, a + level);
      mean[i] = smoothMean(a, b);
      min[i] = mean[i] - Noise;
      max[i] = mean[i] + Noise;
      count[i] = b - a;
    }
    return { form: 'bins', start: from, min, max, mean, count };
  };

  const answer = (r: RegionRequest): RegionAnswer => {
    const served = r.system === ChromosomeSystem || r.system === '17';
    if (!served || !ChromosomeLevels.includes(r.level))
      return {
        ok: false,
        kind: 'not-served',
        issue: issueOf(SourceIssues, 'seq.source.not_served', 'The chromosome serves chr17 at its levels'),
      };
    const start = Math.max(0, r.start);
    const end = Math.min(length, r.end);
    const tables: { -readonly [K in keyof Tables]: Tables[K] } = {};
    if (r.shapes.includes('letters') && r.level === 1)
      tables.letters = { form: 'letters', start, letters: letters(start, end) };
    const genes = r.shapes.includes('ranges') || r.level <= NodesLevel ? genesIn(start, end) : [];
    if (r.shapes.includes('ranges'))
      tables.ranges = {
        form: 'list',
        start: Int32Array.from(genes, (g) => g.start),
        end: Int32Array.from(genes, (g) => g.end),
        strand: Int8Array.from(genes, (g) => g.strand),
        id: categoryColumn(genes.map((g) => g.name)),
      };
    if (r.shapes.includes('values')) tables.values = values(start, end, r.level);
    if (r.level > NodesLevel) return { ok: true, tables };
    // close enough to tell exons apart, each gene's exons come as a node of its own
    const nodes: DynamicNode[] = genes.map((g) => ({
      key: g.name,
      node: exonsNode(ChromosomeSequence, g.name, g.strand === 1 ? '+' : '-', g.exons),
    }));
    return { ok: true, tables, ...(nodes.length ? { nodes } : {}) };
  };

  return { options, coverage, genesIn, letters, smoothMean, answer };
}

/** The chromosome's runtime: a source of the `chromosome` format opens a generated chromosome, answered at once. */
export function chromosomeRuntime(options: ChromosomeOptions = DefaultChromosome): FormatRuntime {
  return {
    name: 'chromosome',
    formats: [ChromosomeFormat],
    async open() {
      const c = chromosome(options);
      return {
        coverage: c.coverage,
        async read(request, signal) {
          if (signal.aborted) throw abortError();
          return c.answer(request);
        },
        dispose() {},
      };
    },
  };
}
